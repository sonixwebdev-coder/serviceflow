const prisma = require('../../lib/prisma');
const { AppError } = require('../utils/errors');
const cache = require('../utils/cache');

const COMPANY_SETTING_KEYS = [
  'companyName',
  'legalName',
  'address',
  'email',
  'phone',
  'website',
  'logoUrl',
  'vatNumber',
  'registrationNumber',
  'bankName',
  'iban',
  'swift',
  'contactPerson',
  'footerNote',
  'gdprNote',
  'additionalNote',
  'rampCount',
];

const DEFAULT_SETTINGS = {
  companyName: process.env.COMPANY_NAME || 'ServiceFlow',
  legalName: process.env.COMPANY_LEGAL_NAME || 'ServiceFlow SRL',
  address: process.env.COMPANY_ADDRESS || 'Str. Exemplu 123, București, România',
  email: process.env.COMPANY_EMAIL || 'contact@serviceflow.ro',
  phone: process.env.COMPANY_PHONE || '+40 700 000 000',
  website: process.env.COMPANY_WEBSITE || 'https://serviceflow.ro',
  logoUrl: process.env.COMPANY_LOGO_URL || '',
  vatNumber: process.env.COMPANY_VAT_NUMBER || process.env.COMPANY_TAX_ID || '',
  registrationNumber: process.env.COMPANY_REGISTRATION || '',
  bankName: process.env.COMPANY_BANK_NAME || '',
  iban: process.env.COMPANY_IBAN || '',
  swift: process.env.COMPANY_SWIFT || '',
  contactPerson: process.env.COMPANY_CONTACT_PERSON || '',
  footerNote:
    process.env.COMPANY_FOOTER_NOTE || 'This document was generated by the ServiceFlow CRM.',
  gdprNote:
    process.env.COMPANY_GDPR_NOTE ||
    'All personal data is processed in accordance with GDPR regulations. Clients may request updates or removal at any time.',
  additionalNote: process.env.COMPANY_ADDITIONAL_NOTE || '',
  rampCount: Number(process.env.COMPANY_RAMP_COUNT || 4),
};

const mapRowsToSettings = (rows) => {
  const settings = {};

  // Build a map of database values
  const dbValues = {};
  rows.forEach((row) => {
    const value = row.value;
    if (value && Object.prototype.hasOwnProperty.call(value, 'value')) {
      dbValues[row.name] = value.value;
    } else if (value !== null && typeof value !== 'undefined') {
      dbValues[row.name] = value;
    }
  });

  // For each setting key, prioritize DB value over DEFAULT_SETTINGS
  COMPANY_SETTING_KEYS.forEach((key) => {
    if (dbValues[key] !== undefined && dbValues[key] !== null && dbValues[key] !== '') {
      settings[key] = dbValues[key];
    } else {
      settings[key] = DEFAULT_SETTINGS[key];
    }
  });

  // Special handling for vatNumber fallback
  if (!settings.vatNumber && settings.taxId) {
    settings.vatNumber = settings.taxId;
  }

  // Special handling for rampCount
  if (dbValues.rampCount !== undefined && dbValues.rampCount !== null) {
    settings.rampCount = Number(dbValues.rampCount) || DEFAULT_SETTINGS.rampCount;
  } else {
    settings.rampCount = DEFAULT_SETTINGS.rampCount;
  }

  return settings;
};

const getCompanySettings = async (options = {}) => {
  const { skipCache = false } = options;

  // Try cache first (unless explicitly skipped)
  if (!skipCache) {
    const cached = await cache.get(cache.companySettingsKey());
    if (cached) {
      return cached;
    }
  }

  const rows = await prisma.companySetting.findMany();
  const settings = mapRowsToSettings(rows);

  // Cache settings for 30 minutes (they rarely change)
  await cache.set(cache.companySettingsKey(), settings, cache.TTL.LONG);

  return settings;
};

const updateCompanySettings = async (payload, currentUser) => {
  if (!currentUser) {
    throw new AppError('Authentication required', 401);
  }

  const updates = COMPANY_SETTING_KEYS.reduce((acc, key) => {
    if (Object.prototype.hasOwnProperty.call(payload, key)) {
      acc[key] = payload[key];
    }
    return acc;
  }, {});

  const keysToUpdate = Object.keys(updates);
  if (!keysToUpdate.length) {
    return getCompanySettings();
  }

  if (Object.prototype.hasOwnProperty.call(updates, 'rampCount')) {
    const parsed = Number(updates.rampCount);
    if (!Number.isFinite(parsed) || parsed < 1) {
      throw new AppError('Ramp count must be a positive number', 400);
    }
    updates.rampCount = Math.floor(parsed);
  }

  await prisma.$transaction(
    keysToUpdate.map((key) =>
      prisma.companySetting.upsert({
        where: { name: key },
        update: { value: { value: updates[key] } },
        create: {
          name: key,
          value: { value: updates[key] },
        },
      })
    )
  );

  // Invalidate settings cache after update
  await cache.del(cache.companySettingsKey());

  return getCompanySettings();
};

module.exports = {
  COMPANY_SETTING_KEYS,
  DEFAULT_SETTINGS,
  getCompanySettings,
  updateCompanySettings,
};
